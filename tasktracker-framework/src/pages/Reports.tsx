// Reports (FR-012, FR-013): filter by employee, project, task, item and dates.
// Team leads see their team only; export is for Manager and Admin only.
import { useState } from 'react';
import { api } from '../api/client';
import { useMe } from '../auth/AuthContext';
import { DateRange } from '../components/DateRange';
import { HoverSelect } from '../components/HoverSelect';
import { Card, Empty, ErrorBox, Loading, PageHead } from '../components/ui';
import { TODAY } from '../config';
import { useLoad } from '../hooks';
import { useRouter } from '../router';
import { download, toCsv } from '../utils/csv';
import { addDays, fmtDay } from '../utils/dates';
import { hours } from '../utils/format';
import { total, useCatalog, workOnly } from './shared';

export function Reports() {
  const me = useMe();
  const { query } = useRouter();
  const [range, setRange] = useState({ from: addDays(TODAY, -30), to: TODAY });
  const [f, setF] = useState({ userId: 0, projectId: Number(query.get('projectId') ?? 0), taskId: 0, itemId: 0 });
  const cat = useCatalog();
  const rows = useLoad(
    () => api.entries({ ...range, userId: f.userId || undefined, projectId: f.projectId || undefined, taskId: f.taskId || undefined, itemId: f.itemId || undefined }),
    [range.from, range.to, f.userId, f.projectId, f.taskId, f.itemId],
  );
  if (cat.loading || !cat.data) return <Loading />;
  const c = cat.data;
  const canExport = me.role === 'manager' || me.role === 'admin';
  const work = workOnly(rows.data ?? []);
  const name = (id: number) => c.users.find((u) => u.id === id)?.name ?? '';
  const table = [['Date', 'Employee', 'Project', 'Task', 'Item', 'Description', 'Hours'], ...work.map((r) => [r.date, name(r.userId), r.project, r.task, r.item, r.remarks, (r.minutes / 60).toFixed(2)])];
  const all = { value: 0, label: 'All' };

  return (
    <>
      <PageHead
        title="Reports"
        sub={me.role === 'team_lead' ? 'Time logged by your team.' : 'Time logged across the organization.'}
        actions={canExport && (
          <>
            <button className="btn ghost" disabled={!work.length} onClick={() => download(`report_${range.from}_${range.to}.csv`, toCsv(table))}>Export CSV</button>
            {/* XLSX is generated by the backend (GET /api/reports/export?format=xlsx); mock mode saves CSV. */}
            <button className="btn ghost" disabled={!work.length} onClick={() => download(`report_${range.from}_${range.to}_xlsx.csv`, toCsv(table))}>Export XLSX</button>
          </>
        )}
      />
      <Card>
        <div className="fbar">
          <HoverSelect label="Employee" value={f.userId} active={!!f.userId} options={[all, ...c.users.filter((u) => u.active).map((u) => ({ value: u.id, label: u.name }))]} onChange={(v) => setF({ ...f, userId: v })} />
          <HoverSelect label="Project" value={f.projectId} active={!!f.projectId} options={[all, ...c.projects.map((p) => ({ value: p.id, label: p.name }))]} onChange={(v) => setF({ ...f, projectId: v, taskId: 0, itemId: 0 })} />
          <HoverSelect label="Task" value={f.taskId} active={!!f.taskId} options={[all, ...c.tasks.filter((t) => t.projectId === f.projectId).map((t) => ({ value: t.id, label: t.name }))]} onChange={(v) => setF({ ...f, taskId: v, itemId: 0 })} />
          <HoverSelect label="Item" value={f.itemId} active={!!f.itemId} options={[all, ...c.items.filter((i) => i.taskId === f.taskId).map((i) => ({ value: i.id, label: i.name }))]} onChange={(v) => setF({ ...f, itemId: v })} />
        </div>
        <DateRange from={range.from} to={range.to} onApply={(from, to) => setRange({ from, to })} />
      </Card>
      <ErrorBox msg={rows.error} />
      <Card title={`${work.length} entries · ${hours(total(work))}`}>
        {rows.loading ? <Loading /> : work.length === 0 ? <Empty>No entries match these filters.</Empty> : (
          <div className="tbl scroll">
            <div className="tr th c6"><span>Date</span><span>Employee</span><span>Project / task / item</span><span>Time</span><span>Remarks</span><span>Hours</span></div>
            {work.slice().reverse().map((r) => (
              <div key={r.id} className="tr c6"><span>{fmtDay(r.date)}</span><span>{name(r.userId)}</span><span>{r.project} / {r.task} / {r.item}</span><span>{r.start}–{r.end}</span><span className="mut ell">{r.remarks}</span><b>{hours(r.minutes)}</b></div>
            ))}
          </div>
        )}
      </Card>
    </>
  );
}
